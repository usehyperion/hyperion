<script lang="ts" module>
	import type { VariantProps } from "#lib/util/styles.js";

	import { tv } from "#lib/util/styles.js";

	export const emptyMediaVariants = tv({
		base: "mb-1 flex shrink-0 items-center justify-center [&_svg]:pointer-events-none [&_svg]:shrink-0",
		variants: {
			variant: {
				default: "bg-transparent",
				icon: "flex size-8 shrink-0 items-center justify-center rounded-control border border-line bg-surface-2 text-fg-muted [&_svg:not([class*='size-'])]:size-4",
